# -*- coding: utf-8 -*-
"""L1 规则调研工具：名字规则能分走多少、噪声在哪、2 KB 够不够。

回答 docs/09 里三个还没测的问题：
  §33.5.4  第一个有效行 / 认格式锚点落在第几行、第几字节
  §33.8    误报源：被名字规则路由、但实际不是载体的文件集中在哪些目录
  覆盖率   C1–C8 八个大类靠「后缀 + 文件名」能覆盖全部文件的多少

用法：
    py -I tests/tools/l1_survey.py --root <源码树> --csv out.csv

关于「分桶」是干什么的（本工具唯一不好懂的地方）：
    我们要决定「L1 每次只读文件开头多少字节」。这个决定没法用一个平均数来做，
    因为分布是长尾的：绝大多数文件第一行就是正文，少数文件前面压着 300 行许可证。
    所以把每个文件的「第一个有效行在第几行 / 第几字节」归到若干区间（桶）里，
    数每个区间有多少文件，就能直接回答「读 2 KB 够不够」：
    如果 97.7% 的文件都落在 2 KB 以内，那读 2 KB 就是对的。
    类比：量打井要挖多深，不报平均深度，而是报「1 米以内的有多少口、1–2 米的有多少口」。
"""
import argparse
import csv
import re
from collections import Counter
from pathlib import Path

# 这些目录不参与统计：VCS 元数据、Python 缓存、构建输出
SKIP_DIRS = {".git", ".repo", "__pycache__", "out"}

# ---- 名字规则的三张表 ----
# 注意：classify() 只查这三张表，一个字节的文件内容都不看。
# 这是故意的——本工具量的是「只靠名字能分走多少」这个下限。

# 按后缀认的大类（C1 脚本、C2 构建描述、C5 链接与符号、C6 C 源码、C8 设备树）
C1_EXT = {".sh", ".bash", ".zsh", ".py", ".pl", ".rb", ".bat", ".ps1"}
C2_EXT = {".mk", ".gn", ".gni", ".cmake", ".bp", ".bb", ".bbappend", ".bbclass", ".inc"}
C5_EXT = {".ld", ".lds", ".map", ".symbols", ".vers"}
C6_EXT = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".inl", ".s"}
C8_EXT = {".dts", ".dtsi", ".overlay"}

# 按完整文件名认的大类。文件名统一转小写后再比，所以这里写小写。
# C2：构建系统入口文件（它们没有统一后缀，只能靠整名）
C2_NAME = {"makefile", "gnumakefile", "cmakelists.txt", "meson.build", "build.gn",
           "sconscript", "kbuild", "meson_options.txt", "meson.options"}
# C3：模块/包清单（声明「这个单元叫什么、依赖谁」）
C3_NAME = {"bundle.json", "ohos.build", "android.bp", "package.json", "control",
           "setup.py", "pyproject.toml", "cargo.toml", "go.mod"}
# C4：板级/产品/工具链配置（为某块板选定取值）
C4_NAME = {"config.json", "boardconfig.mk", "local.conf", "bblayers.conf", "prj.conf",
           "cmakepresets.json", "sdkconfig"}

# 噪声目录：名字命中这些目录的文件算「误报候选」。
# 它们仍会被分类，但要单独计数——因为这些目录里的文件多半不是真正的载体。
NOISE = {"test", "tests", "testing", "third_party", "thirdparty", "3rdparty", "examples",
         "example", "samples", "sample", "docs", "doc", "figures", "images", "assets"}

# 生成物标记：文件开头出现这些话，说明它是「生成出来的，别手改」
GEN_MARK = re.compile(rb"(DO NOT EDIT|auto-?generated|Generated by|autogenerated)", re.I)

# 注释行前缀。找「第一个有效行」时，以这些开头的行都跳过。
COMMENT_PREFIX = (b"#", b"//", b"/*", b"*", b"--", b";", b"<!--", b"%")


def classify(p: Path):
    """只按文件名/后缀给一个类标签；认不出返回 "other"。

    顺序即优先级：先命中先返回。所以同一个文件同时像两类时，只记靠前的那个
    （例如 Android.bp 同时是构建描述和模块清单，这里只记 C2）。
    """
    name = p.name.lower()   # 文件名转小写：Makefile / makefile / MAKEFILE 都认
    ext = p.suffix          # 后缀：注意这里没有转小写，.S / .C 会漏（已知缺陷）

    if ext in C1_EXT:
        return "C1"         # 可执行脚本
    if name in C2_NAME or ext in C2_EXT:
        return "C2"         # 构建描述
    if name in C3_NAME:
        return "C3"         # 模块/包清单
    if name in C4_NAME or name.endswith("_defconfig") or ext == ".defconfig":
        return "C4"         # 板级/产品/工具链配置
    if ext in C5_EXT:
        return "C5"         # 链接脚本与符号表
    if ext in C6_EXT:
        return "C6"         # C/C++ 源码与头文件
    if name.startswith("kconfig"):
        return "C7"         # 开关 schema（Kconfig / Kconfig.debug / Kconfig.defconfig…）
    if ext in C8_EXT:
        return "C8"         # 设备树
    return "other"          # 名字规则认不出


def first_effective_line(data: bytes):
    """返回 (行号, 字节偏移)：第一个「非空且非注释」的行。

    做法：从头逐行看，空行和注释行跳过（同时把它们的字节数累加到 off），
    遇到第一个别的内容就返回。所以返回的偏移 = 正文真正开始的位置。
    整个文件都是注释/空行时返回 (None, None)——这类文件不进分桶。
    """
    off = 0        # 已经跳过的字节数
    lineno = 0     # 已经看过的行数
    for raw in data.splitlines(keepends=True):
        lineno += 1
        s = raw.strip()
        if not s or s.startswith(COMMENT_PREFIX):
            off += len(raw)     # 这一行要跳过，把它的长度记进偏移
            continue
        return lineno, off
    return None, None


def is_binary(data: bytes):
    """前 4 KB 里有 \\x00 就当二进制（图片、可执行文件等），不参与文本统计。"""
    return b"\x00" in data[:4096]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--csv", default=None, help="逐文件明细")
    ap.add_argument("--max-bytes", type=int, default=1 << 20,
                    help="每个文件最多读多少字节（默认 1 MB，够跳过任意长的许可证头）")
    a = ap.parse_args()

    root = Path(a.root)

    # ---- 各种计数器 ----
    rows = []                      # 明细行（写 CSV 用）
    cat_count = Counter()          # 每个大类有多少文件
    noise_hits = Counter()         # 噪声目录名 -> 文件数（含 other）
    noise_routed = Counter()       # 噪声目录里「被路由出去」的文件，按大类
    gen_routed = 0                 # 被路由、且带生成物标记的文件数
    line_buckets = Counter()       # 第一个有效行的行号分布
    byte_buckets = Counter()       # 第一个有效行的字节偏移分布
    text_files = 0                 # 参与文本统计的文件数（非二进制）

    for p in root.rglob("*"):
        # 跳过 VCS 目录、Python 缓存、构建输出，以及所有非文件
        if any(x in SKIP_DIRS for x in p.parts) or not p.is_file():
            continue
        try:
            size = p.stat().st_size
        except OSError:
            continue

        rel = p.relative_to(root).as_posix()
        cat = classify(p)          # 第一步：只按名字分类
        cat_count[cat] += 1

        # ---- 噪声判定：看「目录部分」里有没有噪声名，不看文件名 ----
        parts = {x.lower() for x in p.relative_to(root).parts[:-1]}
        in_noise = bool(parts & NOISE)
        if in_noise:
            noise_hits[category_key(parts)] += 1     # 所有落进噪声目录的文件
            if cat != "other":
                noise_routed[cat] += 1               # 其中被名字规则路由出去的

        # ---- 读文件头（最多 1 MB），供后面三个用途 ----
        head = b""
        try:
            with p.open("rb") as fh:
                head = fh.read(min(size, a.max_bytes))
        except OSError:
            pass

        # 用途一：生成物标记（只看前 4 KB，足够——标记总在文件开头）
        generated = bool(GEN_MARK.search(head[:4096])) if head else False
        if generated and cat != "other":
            gen_routed += 1

        # 用途二/三：二进制判定 + 找第一个有效行
        lineno = boff = None
        if head and not is_binary(head):
            text_files += 1
            lineno, boff = first_effective_line(head)

            # ---- 分桶 ----
            # 这段把「第一个有效行在第几行」归到一个区间里。
            # 循环是「命中就停」：文件只进第一个满足条件的桶，桶之间互斥，
            # 所以各桶百分比加起来是 100%。
            # 因此 line_buckets[5] 装的是「第 2–5 行」，不是「≤5 行」；
            # line_buckets[50] 装的是「第 31–50 行」。
            if lineno:
                for lim in (1, 5, 10, 20, 30, 50):
                    if lineno <= lim:
                        line_buckets[lim] += 1
                        break
                else:
                    line_buckets[999] += 1        # 超过 50 行

                # 字节侧同理：byte_buckets[2048] 装的是「1025–2048 字节」。
                for lim in (512, 1024, 2048, 4096, 8192):
                    if boff <= lim:
                        byte_buckets[lim] += 1
                        break
                else:
                    byte_buckets[99999] += 1      # 超过 8 KB

        if a.csv:
            rows.append(dict(path=rel, cat=cat, size=size, noise=int(in_noise),
                             generated=int(generated), first_line=lineno, first_byte=boff))

    # ---- 输出 ----
    total = sum(cat_count.values())
    print(f"文件 {total}")
    print("\n== 名字规则分走多少 ==")
    for k, v in cat_count.most_common():
        print(f"  {k:<6}{v:>7}  {v/total:>6.1%}")
    covered = total - cat_count["other"]
    print(f"  覆盖（非 other）{covered}/{total} = {covered/total:.1%}")

    print("\n== 噪声目录（按 C1–C8 路由进去的数量）==")
    for k, v in noise_hits.most_common(10):
        print(f"  {k:<28}{v:>7}")
    print(f"  噪声目录里的路由文件合计 {sum(noise_routed.values())}")
    for k, v in noise_routed.most_common():
        print(f"     {k}: {v}")
    print(f"  带「生成物」标记的路由文件 {gen_routed}")

    # 注意：下面打印的 "≤k" 实际表示「落在 k 这个桶里」，
    # 即区间 (上一个边界, k]，不是累计值。百分比各行相加 = 100%。
    print(f"\n== 第一个有效行（文本文件 {text_files}）==")
    for k in (1, 5, 10, 20, 30, 50, 999):
        if line_buckets[k]:
            label = f"≤{k}" if k != 999 else ">50"
            print(f"  行 {label:<6}{line_buckets[k]:>7}  {line_buckets[k]/max(sum(line_buckets.values()),1):>6.1%}")
    print("== 第一个有效行的字节偏移 ==")
    for k in (512, 1024, 2048, 4096, 8192, 99999):
        if byte_buckets[k]:
            label = f"≤{k}B" if k != 99999 else ">8KB"
            print(f"  {label:<8}{byte_buckets[k]:>7}  {byte_buckets[k]/max(sum(byte_buckets.values()),1):>6.1%}")

    if a.csv:
        with open(a.csv, "w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        print(f"\n明细 -> {a.csv}")


def category_key(parts):
    """一个文件可能同时落在多层噪声目录里（如 test/images/），按固定顺序取第一个。"""
    for x in ("third_party", "thirdparty", "3rdparty", "test", "tests", "testing",
              "examples", "example", "samples", "sample", "docs", "doc", "figures",
              "images", "assets"):
        if x in parts:
            return x
    return "?"


if __name__ == "__main__":
    main()
